/**
 * The kernel — wiring, connections and dispatch.
 *
 * `createKernel` is the only entry point an embedding needs: hand it a
 * {@link PlatformHost}, `boot()` it, and open connections. A connection is a
 * socket in the protocol sense — text frames in, text frames out — whether the
 * transport underneath is an in-process bridge, a loopback socket, or (in
 * tests) nothing at all. Everything above the frame boundary is shared.
 *
 * Dispatch rules, unchanged from the desktop listener:
 *
 *  - The first frame must be a `hello`; anything else answers
 *    `UNAUTHENTICATED`. A local kernel accepts any token.
 *  - A method that throws `MethodError` answers its code; anything thrown
 *    that is not a MethodError is a kernel bug and answers `INTERNAL`.
 *  - Frames that fail envelope validation answer `MALFORMED_FRAME` / version
 *    codes and never tear the connection down.
 *
 * Events reach every open connection the moment they are emitted: an approval
 * raised inside a running turn must not wait for some dispatch cycle to
 * notice it.
 */

import type { PlatformHost } from './host/host.ts'
import { fromCallback, type Callback } from './host/host.ts'
import {
  encodeFrame,
  errorFrame,
  eventFrame,
  okFrame,
  parseClientFrame,
  PROTOCOL_VERSION,
  type ClientFrame,
  type ClientRequestFrame,
} from './protocol/frames.ts'
import { MethodError } from './protocol/method-error.ts'
import { DEFAULT_CONFIG, mergeConfig, type KernelConfig } from './core/config.ts'
import { SessionStore } from './core/session-store.ts'
import { InteractionsBroker } from './core/interactions.ts'
import { DeliveryLedger } from './core/delivery.ts'
import { OpenAICompatEngine } from './engine/openai-compat.ts'
import { TurnRunner } from './core/turn-runner.ts'
import { buildMethodTable, type MethodContext } from './core/methods.ts'

const CONFIG_FILE = 'config.json'

/** A client connection to the kernel: text frames in, text frames out. */
export interface KernelConnection {
  /** The device id this connection presents (generated by the kernel). */
  readonly deviceId: string
  /** Deliver one client frame. */
  send(text: string): void
  /** Subscribe to server frames. Returns an unsubscribe function. */
  onFrame(callback: (text: string) => void): () => void
  /** Close the connection. When the last one closes, pending interactions fail closed. */
  close(): void
}

/** The kernel, booted and ready. */
export interface Kernel {
  readonly protocolVersion: number
  /** Open one client connection. */
  openConnection(): KernelConnection
  /** The running configuration (a copy). */
  config(): KernelConfig
  /** The kernel's identity, as the welcome frame carries it. */
  identity(): { hostId: string; hostName: string; home: string; deviceId: string }
}

/** Boot a kernel. Resolves when the session store is loaded. */
export async function createKernel(options: {
  host: PlatformHost
  /** Override the engine adapter; tests inject scripted engines here. */
  engine?: import('./engine/types.ts').EngineAdapter
}): Promise<Kernel> {
  return await KernelImpl.boot(options.host, options.engine)
}

interface ConnectionEntry {
  readonly deviceId: string
  readonly listeners: Set<(text: string) => void>
  closed: boolean
  /** Whether a hello has been accepted on this connection. */
  handshaken: boolean
}

export class KernelImpl {
  readonly #host: PlatformHost
  #config: KernelConfig = DEFAULT_CONFIG
  #store!: SessionStore
  #broker!: InteractionsBroker
  #runner!: TurnRunner
  readonly #ledger = new DeliveryLedger()
  #hostId = ''
  #deviceId = ''
  readonly #connections = new Map<number, ConnectionEntry>()
  #nextConnectionId = 0
  /** Prompts waiting for their session's running turn to end. */
  readonly #queued = new Map<string, { text: string; requestId: string; clientTimeZone?: string }[]>()

  readonly #engineOverride: import('./engine/types.ts').EngineAdapter | undefined

  private constructor(host: PlatformHost, engine?: import('./engine/types.ts').EngineAdapter) {
    this.#host = host
    this.#engineOverride = engine
  }

  static async boot(host: PlatformHost, engine?: import('./engine/types.ts').EngineAdapter): Promise<KernelImpl> {
    const kernel = new KernelImpl(host, engine)
    await kernel.#boot()
    return kernel
  }

  async #boot(): Promise<void> {
    const patch = await this.#loadConfigPatch()
    this.#config = mergeConfig(DEFAULT_CONFIG, patch)

    this.#hostId = await this.#kvEnsure('kernel.hostId')
    this.#deviceId = await this.#kvEnsure('kernel.deviceId')

    this.#store = new SessionStore(this.#host, `${this.#host.home}/workspace`)
    await this.#store.load()

    this.#broker = new InteractionsBroker((event, data) => this.#emit(event, data))
    const engine = this.#engineOverride ?? new OpenAICompatEngine(this.#host, () => this.#config)
    this.#runner = new TurnRunner({
      host: this.#host,
      store: this.#store,
      engine,
      broker: this.#broker,
      config: () => this.#config,
    })

    this.#host.log('info', `kernel booted: ${this.#hostId}, ${this.#store.list().length} sessions`)
  }

  async #kvEnsure(key: string): Promise<string> {
    const existing = await fromCallback<string | null>((cb: Callback<string | null>) => this.#host.kv.get(key, cb))
    if (existing !== null && existing !== '') return existing
    const fresh = this.#host.uuid()
    await fromCallback<void>((cb: Callback<void>) => this.#host.kv.set(key, fresh, cb))
    return fresh
  }

  async #loadConfigPatch(): Promise<Record<string, unknown>> {
    const text = await fromCallback<string | null>((cb: Callback<string | null>) => this.#host.fs.readText(CONFIG_FILE, cb))
    if (text === null || text === '') return {}
    try {
      const parsed: unknown = JSON.parse(text)
      if (typeof parsed === 'object' && parsed !== null && !Array.isArray(parsed)) {
        return parsed as Record<string, unknown>
      }
      this.#host.log('warn', 'config.json is not an object; defaults apply')
    } catch {
      this.#host.log('warn', 'config.json is not valid JSON; defaults apply')
    }
    return {}
  }

  // -- Kernel API ----------------------------------------------------------

  get protocolVersion(): number {
    return PROTOCOL_VERSION
  }

  config(): KernelConfig {
    return JSON.parse(JSON.stringify(this.#config)) as KernelConfig
  }

  identity(): { hostId: string; hostName: string; home: string; deviceId: string } {
    return {
      hostId: this.#hostId,
      hostName: this.#host.hostName,
      home: this.#host.home,
      deviceId: this.#deviceId,
    }
  }

  openConnection(): KernelConnection {
    const entry: ConnectionEntry = {
      deviceId: this.#host.uuid(),
      listeners: new Set<(text: string) => void>(),
      closed: false,
      handshaken: false,
    }
    const id = (this.#nextConnectionId += 1)
    this.#connections.set(id, entry)

    const close = () => {
      if (entry.closed) return
      entry.closed = true
      entry.listeners.clear()
      this.#connections.delete(id)
      // Fail closed only when the last client is gone: a second screen is
      // still there to answer.
      if (this.#connections.size === 0) this.#broker.setClientCount(0)
    }

    const connection: KernelConnection = {
      deviceId: entry.deviceId,
      send: (text: string) => {
        if (entry.closed) return
        const parsed = parseClientFrame(text)
        if (!parsed.ok) {
          // Envelope-level failures answer and survive, exactly like the
          // desktop listener: a bad frame is not a dead socket.
          this.#deliver(entry, encodeFrame(errorFrame(parsed.code, parsed.message)))
          return
        }
        const frame = parsed.frame
        if (frame.type === 'hello') {
          // Every hello re-answers the welcome, harmlessly; the first one
          // opens the connection.
          entry.handshaken = true
          this.#deliver(entry, this.#welcomeFrame())
          return
        }
        if (!entry.handshaken) {
          this.#deliver(
            entry,
            encodeFrame(errorFrame('UNAUTHENTICATED', 'the first frame must be a hello')),
          )
          return
        }
        void this.#dispatch(frame, entry)
      },
      onFrame: (callback: (text: string) => void) => {
        entry.listeners.add(callback)
        return () => {
          entry.listeners.delete(callback)
        }
      },
      close,
    }
    return connection
  }

  #welcomeFrame(): string {
    const identity = this.identity()
    return encodeFrame({
      v: PROTOCOL_VERSION,
      type: 'welcome',
      hostId: identity.hostId,
      hostName: identity.hostName,
      protocolVersion: PROTOCOL_VERSION,
      home: identity.home,
      deviceId: this.#deviceId,
    })
  }

  #deliver(entry: ConnectionEntry, text: string): void {
    // Best-effort, like every desktop notification path: a failing sink must
    // never fail the state change that produced the frame.
    for (const listener of entry.listeners) {
      try {
        listener(text)
      } catch (error) {
        this.#host.log('warn', `a frame sink threw: ${error instanceof Error ? error.message : String(error)}`)
      }
    }
  }

  #emit(event: string, data: unknown): void {
    const text = encodeFrame(eventFrame(event, data))
    for (const entry of this.#connections.values()) {
      if (!entry.closed) this.#deliver(entry, text)
    }
  }

  async #dispatch(frame: ClientFrame, entry: ConnectionEntry): Promise<void> {
    if (frame.type === 'hello') return // handled in send()
    const request = frame as ClientRequestFrame
    const id = request.id
    const deliver = (text: string) => this.#deliver(entry, text)

    // Delivery hooks are per-request on purpose: a concurrent request's page
    // must never move another request's ledger cursor.
    const deliveryHooks: (() => void)[] = []

    try {
      const table = buildMethodTable()
      const handler = table[request.type]
      if (handler === undefined) {
        deliver(encodeFrame(errorFrame('NOT_IMPLEMENTED', `the kernel does not implement "${request.type}"`, id)))
        return
      }

      const context: MethodContext = {
        kernel: this,
        deviceId: entry.deviceId,
        onDelivered: (hook) => {
          deliveryHooks.push(hook)
        },
      }

      const result = await handler(request.payload, context)
      deliver(encodeFrame(okFrame(id, result)))
      // Hooks run only after the ok frame went out: "delivered", not
      // "exists" — the ledger's whole distinction.
      for (const hook of deliveryHooks) hook()
    } catch (error) {
      if (error instanceof MethodError) {
        deliver(encodeFrame(errorFrame(error.code, error.message, id, error.retryable)))
      } else {
        this.#host.log(
          'error',
          `"${request.type}" failed: ${error instanceof Error ? (error.stack ?? error.message) : String(error)}`,
        )
        deliver(
          encodeFrame(errorFrame('INTERNAL', error instanceof Error ? error.message : String(error), id)),
        )
      }
    }
  }

  // -- Internals the method table uses ------------------------------------

  get store(): SessionStore {
    return this.#store
  }

  get runner(): TurnRunner {
    return this.#runner
  }

  get broker(): InteractionsBroker {
    return this.#broker
  }

  get ledger(): DeliveryLedger {
    return this.#ledger
  }

  get host(): PlatformHost {
    return this.#host
  }

  /** Whether the kernel holds a session open for prompts (queueing check). */
  isSessionRunning(sessionId: string): boolean {
    return this.#runner.isRunning(sessionId)
  }

  updateConfig(patch: Record<string, unknown>): KernelConfig {
    this.#config = mergeConfig(this.#config, patch)
    return this.#config
  }

  async persistConfig(): Promise<void> {
    await fromCallback<void>((cb: Callback<void>) => this.#host.fs.writeText(CONFIG_FILE, JSON.stringify(this.#config, null, 2), cb))
  }

  /**
   * Accept a prompt.
   *
   * `session.prompt` never runs the turn inline: it accepts, and the turn
   * runs in the background — the client reads its progress through the same
   * polling the desktop protocol uses. A prompt that arrives mid-turn queues;
   * the queue drains turn by turn.
   */
  acceptPrompt(
    sessionId: string,
    prompt: { text: string; requestId: string; clientTimeZone?: string },
  ): void {
    if (this.#runner.isRunning(sessionId)) {
      const queue = this.#queued.get(sessionId) ?? []
      queue.push(prompt)
      this.#queued.set(sessionId, queue)
      return
    }
    this.#runTurn(sessionId, prompt)
  }

  #runTurn(
    sessionId: string,
    prompt: { text: string; requestId: string; clientTimeZone?: string },
  ): void {
    void (async () => {
      try {
        await this.#runner.run({
          sessionId,
          text: prompt.text,
          requestId: prompt.requestId,
          ...(prompt.clientTimeZone !== undefined ? { clientTimeZone: prompt.clientTimeZone } : {}),
          signal: unabortable,
        })
      } catch (error) {
        this.#host.log(
          'error',
          `turn failed for ${sessionId}: ${error instanceof Error ? error.message : String(error)}`,
        )
      } finally {
        const queue = this.#queued.get(sessionId)
        const next = queue?.shift()
        if (queue !== undefined && queue.length === 0) this.#queued.delete(sessionId)
        if (next !== undefined) this.#runTurn(sessionId, next)
      }
    })()
  }
}

const unabortable = {
  get aborted() {
    return false
  },
  onAbort: () => {},
}
