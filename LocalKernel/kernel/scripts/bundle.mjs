/**
 * Build the kernel bundle and the Swift file that embeds it.
 *
 * Two outputs, one source of truth:
 *
 *  - `dist/mizar-kernel.js` — the platform-neutral IIFE bundle. This is what
 *    an Android host (or any JS engine) evaluates; it is also readable, which
 *    is what makes the embedded copy auditable.
 *  - `MizarKit/Sources/MizarKit/Kernel/KernelBundle.swift` — the same bytes as
 *    a generated Swift string constant, checked in. The App builds without
 *    Node installed, and the Swift tests run the real bundle, so the embedded
 *    copy cannot drift from the tested one: it *is* the tested one.
 *
 * The Swift literal is JSON-escaped (JSON's escapes are a subset of Swift's)
 * and emitted as a concatenation of bounded chunks: one several-hundred-KB
 * line makes the Swift parser report nonsense, and the concatenation folds
 * into one constant at compile time. Chunks are escaped per chunk, never
 * across one, so no escape sequence is ever cut in half.
 */

import { build } from 'esbuild'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const kernelRoot = join(here, '..')
const repoRoot = join(kernelRoot, '..', '..')

const result = await build({
  entryPoints: [join(kernelRoot, 'src/index.ts')],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  platform: 'neutral',
  globalName: 'MizarKernel',
  minify: true,
  write: false,
  legalComments: 'inline',
})

const code = result.outputFiles[0].text

// 1. The standalone bundle.
mkdirSync(join(kernelRoot, 'dist'), { recursive: true })
writeFileSync(join(kernelRoot, 'dist/mizar-kernel.js'), code)

// 2. The generated Swift file.
const escapedChunks = []
const chunkChars = 8000
for (let index = 0; index < code.length; index += chunkChars) {
  escapedChunks.push(JSON.stringify(code.slice(index, index + chunkChars)))
}
if (escapedChunks.length === 0) escapedChunks.push('""')
const LF = String.fromCharCode(10)
const swiftExpression = escapedChunks.join(' +' + LF + '        ')

const header = [
  '//',
  '//  KernelBundle.swift',
  '//  MizarKit',
  '//',
  '//  GENERATED by LocalKernel/kernel/scripts/bundle.mjs — do not edit by hand.',
  '//  Rebuild with: (cd LocalKernel/kernel && npm run build)',
  '//',
  "//  The local kernel's compiled bundle, embedded as a string so the App target",
  '//  builds without a Node toolchain and the Swift tests run exactly the bytes',
  '//  the TypeScript tests ran. The source of truth is LocalKernel/kernel/src;',
  '//  this file is a build artifact that happens to be version-controlled.',
  '//',
  '//  The kernel inside speaks Mizar protocol v1 and exposes',
  '//  MizarKernel.createKernel({ host }) — see',
  '//  LocalKernel/docs/kernel-api.md for the wire contract.',
  '//',
  '',
  'import Foundation',
  '',
  'public enum KernelBundle {',
  '    /// The compiled kernel, as one JavaScript program.',
  '    public static let javaScriptSource: String =',
]

const footer = ['', '}', '']

const lines = [...header, '        ' + swiftExpression, ...footer]
const swiftPath = join(repoRoot, 'MizarKit/Sources/MizarKit/Kernel/KernelBundle.swift')
mkdirSync(dirname(swiftPath), { recursive: true })
writeFileSync(swiftPath, lines.join(LF))

const sizeKb = Math.round(Buffer.byteLength(code, 'utf8') / 10.24) / 100
console.log('bundle: dist/mizar-kernel.js (' + sizeKb + ' KB, ' + escapedChunks.length + ' chunks)')
console.log('swift:  ' + swiftPath)
